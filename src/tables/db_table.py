def learnings(class_id):
    """某个职业的天生技能 → [(等级, 技能 id), ...]；没有就返回 []。"""
    try:
        return list(CLASS_LEARNINGS.get(int(class_id), ()))
    except (TypeError, ValueError):
        return []

