def _v201_fallback(baby_id):
    """V2.201 专用回退：**按 id 区间**判断类型。

    ⚠ 资质数值是**基准值**不是真值 —— 真正的 `$baby` 表在 V2.201 里是
    **运行时动态生成**的（脚本里只读不赋，`Data/` 下也没有 Babies.rvdata2），
    静态拿不到。所以这里只保证「加得出来、不被过滤」，数值靠 `SPECIES`
    同档位近似。**界面上应当提示「资质为估算值」。**

    返回 None 表示「这个 id 根本不是 V2.201 的召唤兽」（比如 playable 角色），
    让调用方照旧把它过滤掉 —— 宁缺毋滥。
    """
    i = int(baby_id)
    if i not in V201_BABY_IDS:
        return None                    # 不是召唤兽（例如 1~20 的玩家角色）
    lo, hi = GOD_ID_RANGE
    if lo <= i <= hi:
        cfg = dict(POOLS['神兽资质'])
    else:
        cfg = dict(_V201_NORMAL)
    cfg['inferred'] = True
    return cfg


def config_of(baby_id, data_key=None):
    """取某种召唤兽的配置：备注池 → id 查表 → **V2.201 区间回退**。

    最后一档是 2026-10-03 加的：V2.201 既没有池标记、也不在尝鲜版的
    `SPECIES` 范围里，没有它这 107 只会被 `Babies.candidates()` 整个过滤掉，
    表现为「新增召唤兽」列表**少了一大半**。
    """
    if data_key and data_key in POOLS:
        return POOLS[data_key]
    got = SPECIES.get(int(baby_id))
    if got:
        return got
    return _v201_fallback(baby_id)

